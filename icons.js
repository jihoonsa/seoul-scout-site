// The trade's icon as inline SVG in the text colour, or "" for a trade without one
export function tradeIcon(trade) {
  const shapes = SHAPES[trade];
  if (!shapes) return "";
  return `<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${shapes}</svg>`;
}
