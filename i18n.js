const TYPE_NAMES = {
  "Office & visitor core": { ko: "오피스·방문객 중심지", en: "Office & visitor hub" },
  "Family neighborhoods": { ko: "가족 주거지", en: "Family neighborhood" },
  "Young adults & students": { ko: "청년·학생가", en: "Young adults & students" },
  "Foreign-resident neighborhoods": { ko: "외국인 거주지", en: "Foreign-resident area" },
  "Older residential": { ko: "고령 주거지", en: "Older residential" },
};

const ZONE_NAMES = {
  Central: { ko: "도심권", en: "Central" }, Northeast: { ko: "동북권", en: "Northeast" },
  Northwest: { ko: "서북권", en: "Northwest" }, Southwest: { ko: "서남권", en: "Southwest" },
  Southeast: { ko: "동남권", en: "Southeast" },
};

let language = "en";
let tradeNamesEn = {};

export function setLanguage(next) {
  language = next === "ko" ? "ko" : "en";
  document.documentElement.lang = language;
}

export function getLanguage() {
  return language;
}

export function setTradeNamesEn(names) {
  tradeNamesEn = names;
}

export function t(key, ...args) {
  const entry = TEXT[language][key] ?? TEXT.ko[key];
  return typeof entry === "function" ? entry(...args) : entry;
}

export function tradeName(tradeKo) {
  return language === "en" ? (tradeNamesEn[tradeKo] ?? tradeKo) : tradeKo;
}

// Place names (dongs.json carries the English ones, D68): "용답동" / "Yongdap-dong"
export function placeName(dong) {
  return language === "en" ? dong.dong_en : dong.dong.split(" ")[1];
}

export function guName(dong) {
  return language === "en" ? dong.gu_en : dong.gu;
}

// The rent survey point a report names: "왕십리" / "Wangsimni"
export function surveyPointName(dong) {
  return language === "en" ? dong.info.rent_area_en : dong.info.rent_area;
}

// "성동구 용답동" / "Yongdap-dong, Seongdong-gu"
export function fullPlaceName(dong) {
  return language === "en" ? `${dong.dong_en}, ${dong.gu_en}` : dong.dong;
}

export function typeName(type) {
  return TYPE_NAMES[type]?.[language] ?? type;
}

export function zoneName(zone) {
  return ZONE_NAMES[zone]?.[language] ?? zone;
}

export function groupName(group) {
  return language === "en" ? group.en : group.ko;
}

export function formatNumber(value) {
  if (language === "ko" && value >= 10000) {
    return `${(value / 10000).toLocaleString("ko-KR", { maximumFractionDigits: 1 })}만`;
  }
  return Math.round(value).toLocaleString(language === "ko" ? "ko-KR" : "en-US");
}

export function formatWon(value) {
  // Quarterly sales: 만 원 / 억 원 in Korean, ₩ millions in English
  if (language === "en") return `₩${(value / 1e6).toLocaleString("en-US", { maximumFractionDigits: value >= 1e8 ? 0 : 1 })}M`;
  if (value >= 1e8) return `${(value / 1e8).toLocaleString("ko-KR", { maximumFractionDigits: 1 })}억 원`;
  return `${Math.round(value / 1e4).toLocaleString("ko-KR")}만 원`;
}

export function formatPrice(value) {
  // One payment (a few thousand to tens of thousands of won), to the nearest 100 won
  const rounded = Math.round(value / 100) * 100;
  return language === "en" ? `₩${rounded.toLocaleString("en-US")}` : `${rounded.toLocaleString("ko-KR")}원`;
}
