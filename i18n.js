// Korean subject particle: 카페가, 편의점이 (이 after a final consonant)
function subject(word) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  const hasFinalConsonant = code >= 0 && code <= 11171 && code % 28 !== 0;
  return `${word}${hasFinalConsonant ? "이" : "가"}`;
}

// The topic marker 은/는, by the same final-consonant rule
function topic(word) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  const hasFinalConsonant = code >= 0 && code <= 11171 && code % 28 !== 0;
  return `${word}${hasFinalConsonant ? "은" : "는"}`;
}

// The object particle 을/를, by the same rule: 카페를, 레이저태그장을
function object(word) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  const hasFinalConsonant = code >= 0 && code <= 11171 && code % 28 !== 0;
  return `${word}${hasFinalConsonant ? "을" : "를"}`;
}

function capital(word) {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

